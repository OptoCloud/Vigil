using System.Text.Json.Nodes;
using Vigil.Core.Protocol;

namespace Vigil.Core.Tests;

/// <summary>
/// vigil-core's HTTP API as an OpenAPI 3.1 document, for whoever would rather point a tool at
/// vigil than read the README's table. Written here, by hand, and to core/openapi.json by
/// <c>ApiTests.TheOpenApiDocumentIsCurrentAndDescribesEveryRoute</c>, which also fails when
/// a route is mapped that this does not describe, or described that is not mapped.
/// </summary>
/// <remarks>
/// By hand rather than generated from the routes: ASP.NET's generator describes a handler's
/// parameters, and what a reader needs is what this says in words (which values a parameter
/// takes, when the answer is a 503). The response bodies are not described twice: each
/// example is the sample core/contract.json already holds for that type, so the two files
/// cannot disagree about a field.
/// </remarks>
internal static class OpenApiDocument
{
    private static JsonNode Sample(string type) =>
        ContractFiles.Load(ContractFiles.Core)["types"]![type]?.DeepClone() ?? throw new InvalidOperationException($"core/contract.json has no {type}");

    private static JsonObject Json(string description, JsonNode example) => new()
    {
        ["description"] = description,
        ["content"] = new JsonObject { ["application/json"] = new JsonObject { ["example"] = example } },
    };

    private static JsonObject Text(string description, string mediaType = "text/plain") => new()
    {
        ["description"] = description,
        ["content"] = new JsonObject { [mediaType] = new JsonObject { ["schema"] = new JsonObject { ["type"] = "string" } } },
    };

    private static JsonObject Query(string name, string description, JsonObject schema, bool required = false) => new()
    {
        ["name"] = name,
        ["in"] = "query",
        ["required"] = required,
        ["description"] = description,
        ["schema"] = schema,
    };

    private static JsonObject Enumeration<T>()
        where T : struct, Enum => new()
        {
            ["type"] = "string",
            ["enum"] = new JsonArray([.. Enum.GetValues<T>().Select(value => System.Text.Json.JsonSerializer.SerializeToNode(value, VigilJson.Options))]),
        };

    private static JsonObject Get(string summary, JsonObject responses, params JsonNode[] parameters) => new()
    {
        ["get"] = new JsonObject
        {
            ["summary"] = summary,
            ["parameters"] = new JsonArray(parameters),
            ["responses"] = responses,
        },
    };

    private static JsonObject Unavailable => Text("The database could not be reached.");

    public static JsonObject Generate() => new()
    {
        ["openapi"] = "3.1.0",
        ["info"] = new JsonObject
        {
            ["title"] = "vigil-core",
            ["summary"] = "The hardware state of one NAS host, read-only.",
            ["description"] =
                "Every route is a GET that changes nothing, and none needs authentication: what is served is published (ADR-023). "
                + "Each client address gets 200 requests in a burst and 20 a second after that; past it the answer is 429. "
                + "Generated by the vigil-core tests; do not edit. The examples are core/contract.json's.",
            ["license"] = new JsonObject { ["name"] = "AGPL-3.0-or-later", ["identifier"] = "AGPL-3.0-or-later" },
            // The API has no version of its own: it is whatever the release that serves it is.
            ["version"] = "unversioned",
        },
        ["paths"] = new JsonObject
        {
            ["/health"] = Get("Liveness: 200 once running, whatever else is wrong.", new JsonObject { ["200"] = Text("The text \"ok\".") }),
            ["/api/status"] = Get(
                "Readiness, and the running version.",
                new JsonObject
                {
                    ["200"] = Json("The runtime's loop is turning and vigild is connected.", Sample(nameof(StatusResponse))),
                    ["503"] = Json("Not ready. The same body, with ready false.", Sample(nameof(StatusResponse))),
                }),
            ["/metrics"] = Get(
                "The current state as Prometheus gauges. What is unknown is absent, never zero.",
                new JsonObject { ["200"] = Text("Prometheus text exposition format, version 0.0.4.") }),
            ["/api/live"] = Get(
                "Server-Sent Events: the current state on connect, then every change.",
                new JsonObject
                {
                    ["200"] = Text(
                        "A stream. Each event's data is one JSON message whose \"type\" says which (core/contract.json, liveMessages). "
                        + "An event named \"keepalive\" follows 20 seconds of quiet.",
                        "text/event-stream"),
                    ["503"] = Text("Too many live streams are open: 64 in all, 8 from one client."),
                }),
            ["/api/history"] = Get(
                "Chart history for one range, bucketed.",
                new JsonObject
                {
                    ["200"] = Json("Every series as [epochMillis, value] points.", Sample(nameof(HistoryResponse))),
                    ["400"] = Text("range is missing or not one of the ranges, or to is not a time in the past."),
                    ["503"] = Unavailable,
                },
                Query("range", "How long a window, which also sets the resolution.", Enumeration<RangeKey>(), required: true),
                Query("to", "Where the window ends, in milliseconds since 1970, for a look further back. Now when omitted.", new JsonObject { ["type"] = "integer" })),
            ["/api/events"] = Get(
                "The event log, newest first. An empty list when the database is down.",
                new JsonObject
                {
                    ["200"] = Json("A page of events.", new JsonArray(Sample(nameof(EventRecord)))),
                    ["400"] = Text("A parameter is out of range."),
                },
                Query("limit", "How many, 50 when omitted.", new JsonObject { ["type"] = "integer", ["minimum"] = 1, ["maximum"] = 200 }),
                Query("before", "Only events older than the one with this id: the oldest id of the page before.", new JsonObject { ["type"] = "integer", ["minimum"] = 1 }),
                Query("severity", "Only this severity and worse.", Enumeration<Severity>())),
            ["/api/drives/{wwn}/history"] = Get(
                "One drive's recorded SMART changes, newest first, at most 200.",
                new JsonObject
                {
                    ["200"] = Json("A row for each time a count moved. Empty for a drive vigil has never seen.", new JsonArray(Sample(nameof(DriveHealthRecord)))),
                    ["400"] = Text("Not a drive name."),
                    ["503"] = Unavailable,
                },
                new JsonObject
                {
                    ["name"] = "wwn",
                    ["in"] = "path",
                    ["required"] = true,
                    ["description"] = "The drive's stable name, as the live stream gives it.",
                    ["schema"] = new JsonObject { ["type"] = "string", ["maxLength"] = 128 },
                }),
        },
    };

    /// <summary>
    /// True when core/openapi.json already says exactly this. Otherwise it is rewritten and
    /// the answer is false, so the test fails once and the change cannot go unnoticed, as for
    /// the contract files.
    /// </summary>
    public static bool IsOnDiskOrRewrite(JsonObject document)
    {
        var options = new System.Text.Json.JsonSerializerOptions
        {
            WriteIndented = true,
            IndentSize = 2,
            NewLine = "\n",
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        };
        var generated = document.ToJsonString(options) + "\n";
        if (File.Exists(ContractFiles.OpenApi) && File.ReadAllText(ContractFiles.OpenApi).ReplaceLineEndings("\n") == generated)
        {
            return true;
        }

        File.WriteAllText(ContractFiles.OpenApi, generated);
        return false;
    }
}
